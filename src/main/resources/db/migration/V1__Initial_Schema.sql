CREATE TABLE customer
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    name       VARCHAR(255),
    email      VARCHAR(255),
    phone      VARCHAR(255),
    address    VARCHAR(255),
    CONSTRAINT pk_customer PRIMARY KEY (id)
);

CREATE TABLE order_item
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    order_id   BIGINT                                  NOT NULL,
    product_id BIGINT                                  NOT NULL,
    quantity   BIGINT                                  NOT NULL,
    unit_price DECIMAL                                 NOT NULL,
    subtotal   DECIMAL                                 NOT NULL,
    CONSTRAINT pk_orderitem PRIMARY KEY (id)
);

CREATE TABLE product
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at     TIMESTAMP WITHOUT TIME ZONE,
    updated_at     TIMESTAMP WITHOUT TIME ZONE,
    created_by     VARCHAR(255),
    updated_by     VARCHAR(255),
    name           VARCHAR(255),
    description    VARCHAR(255),
    stock_quantity BIGINT                                  NOT NULL,
    price          DECIMAL                                 NOT NULL,
    deleted_at     TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_product PRIMARY KEY (id)
);

CREATE TABLE sales_order
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at   TIMESTAMP WITHOUT TIME ZONE,
    updated_at   TIMESTAMP WITHOUT TIME ZONE,
    created_by   VARCHAR(255),
    updated_by   VARCHAR(255),
    order_date   TIMESTAMP WITHOUT TIME ZONE,
    customer_id  BIGINT,
    total_amount DECIMAL                                 NOT NULL,
    CONSTRAINT pk_sales_order PRIMARY KEY (id)
);

CREATE TABLE user_account
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    updated_at      TIMESTAMP WITHOUT TIME ZONE,
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255),
    username        VARCHAR(255),
    name            VARCHAR(255),
    hashed_password VARCHAR(255)                            NOT NULL,
    role            VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_user_account PRIMARY KEY (id)
);

ALTER TABLE user_account
    ADD CONSTRAINT uc_user_account_username UNIQUE (username);

ALTER TABLE order_item
    ADD CONSTRAINT FK_ORDERITEM_ON_ORDER FOREIGN KEY (order_id) REFERENCES sales_order (id);

ALTER TABLE order_item
    ADD CONSTRAINT FK_ORDERITEM_ON_PRODUCT FOREIGN KEY (product_id) REFERENCES product (id);

ALTER TABLE sales_order
    ADD CONSTRAINT FK_SALES_ORDER_ON_CUSTOMER FOREIGN KEY (customer_id) REFERENCES customer (id);